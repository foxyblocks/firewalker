// Writes include/generated/recipe_budget.h, the recipes the `recipe_budget` firmware build measures
// on a real board: everything in patterns/, on a real boot's layout, and the heaviest recipes the
// format allows, on a real boot's layout and on the uncut strip. It's git-ignored, since it's only for that bench test. Run it with
// `bun run budget-recipes` before building that environment.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { BENCH_STRIP, BOOT_3EB5, type StripLayout } from "../src/engine/strip.ts";
import { compileRecipe } from "../src/recipe/compile.ts";
import { newLayer } from "../src/recipe/spec.ts";
import { RECIPE_FORMAT, RECIPE_VERSION, type Blend, type Layer, type LayerType, type Recipe } from "../src/recipe/types.ts";

const PATTERNS_DIR = fileURLToPath(new URL("../../patterns/", import.meta.url));
const OUT_DIR = fileURLToPath(new URL("../../include/generated/", import.meta.url));

function eight(name: string, type: LayerType, overrides: (i: number) => Record<string, unknown>): Recipe {
  const layers = Array.from({ length: 8 }, (_, i) => ({ ...newLayer(type), ...overrides(i) }) as Layer);
  return { format: RECIPE_FORMAT, version: RECIPE_VERSION, name, description: "", layers };
}

const COLORS = ["#ff2000", "#20ff40", "#2040ff"];
const BLENDS: Blend[] = ["over", "add", "max", "multiply"];

// The worst each kind of layer can do. Every one is a legal recipe that fits in a flash entry.
const HEAVY: Recipe[] = [
  // Every pixel, from a palette, through every layer, with all the blends.
  eight("heavy-fill", "fill", (i) => ({ spread: "ring", palette: COLORS.slice(0, 2), repeat: 3, blend: BLENDS[i % 4], opacity: 0.8 })),
  // Slow, long fronts that pile up. Each layer can hold 16, each 60 pixels long.
  eight("heavy-trail", "trail", () => ({ trigger: "any", palette: COLORS, speed: 5, length: 60, maxFronts: 16, brightness: 1, blend: "add" })),
  // Every pixel twinkling for a long time, on every layer.
  eight("heavy-sprkl", "sparkle", () => ({ palette: COLORS, density: 200, fadeMs: 10000 })),
  // The most comets, the longest tails, painted on both sides of the foot.
  eight("heavy-foot", "chase", () => ({ path: "foot", palette: COLORS, count: 8, length: 60, speed: 60, blend: "add" })),
  eight("heavy-ring", "chase", () => ({ path: "ring", palette: COLORS, count: 8, length: 60, speed: 60, blend: "add" })),
];

const kept = readdirSync(PATTERNS_DIR)
  .filter((file) => file.endsWith(".json"))
  .sort()
  .map((file) => JSON.parse(readFileSync(`${PATTERNS_DIR}${file}`, "utf8")) as Recipe);

const cases: { recipe: Recipe; layout: StripLayout }[] = [
  ...kept.map((recipe) => ({ recipe, layout: BOOT_3EB5 })),
  ...HEAVY.map((recipe) => ({ recipe, layout: BOOT_3EB5 })),
  ...HEAVY.map((recipe) => ({ recipe, layout: BENCH_STRIP })),
];

const arrays: string[] = [];
const rows: string[] = [];
cases.forEach(({ recipe, layout }, i) => {
  const compiled = compileRecipe(recipe);
  if (!compiled.ok) throw new Error(`${recipe.name}: ${compiled.errors.join(" ")}`);
  console.log(`${recipe.name} on ${layout.count} px: ${compiled.size} bytes`);
  arrays.push(`static const uint8_t BUDGET_RECIPE_${i}[] = {${[...compiled.bytes].join(", ")}};`);
  rows.push(`  {${layout.count}, ${layout.toe}, ${layout.heel}, BUDGET_RECIPE_${i}, sizeof(BUDGET_RECIPE_${i})},`);
});

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  `${OUT_DIR}recipe_budget.h`,
  [
    "#pragma once",
    "",
    "// Generated by `bun run budget-recipes`. Not checked in. See src/modes/recipe_budget.cpp.",
    "",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
    ...arrays,
    "",
    "struct BudgetCase {",
    "  uint16_t count;",
    "  uint16_t toe;",
    "  uint16_t heel;",
    "  const uint8_t* bytes;",
    "  size_t size;",
    "};",
    "",
    "static const BudgetCase BUDGET_CASES[] = {",
    ...rows,
    "};",
    "",
  ].join("\n"),
);
console.log("Wrote include/generated/recipe_budget.h");
