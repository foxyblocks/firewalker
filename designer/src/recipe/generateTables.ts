// Writes include/generated/recipe_tables.h: the recipe format's numbers and field layout, for the
// firmware's decoder. spec.ts and types.ts stay the one place a range or a field order lives, and
// the firmware reads this file instead of keeping a second copy.
//
// The decoder walks a layer's fields in order using these tables. Each field also has a slot, which
// is where the decoded value goes in a layer's arrays, so the engine can name it, as in
// `layer.knobs[RecipeSlot::TrailSpeed]`. Every layer's blend and opacity are in slot 0 of their
// arrays, so code that handles any layer type can find them.
//
// `bun run build-recipes` writes this file, and a test fails if it's out of date.

import { MAX_COMPILED_BYTES, LAYER_CODES } from "./compile.ts";
import { fieldsFor, STOMP_FADE, WAVE_PERIOD, type Field } from "./spec.ts";
import { BLENDS, CHASE_PATHS, MAX_LAYERS, MAX_NAME_LENGTH, MAX_PALETTE_STOPS, MIN_RECIPE_VERSION, RECIPE_VERSION, SOURCES, SPREADS, TRAIL_ORIGINS, TRIGGERS, type LayerType } from "./types.ts";
import { RESERVED_NAMES } from "./validate.ts";

const pascal = (words: string): string =>
  words
    .split(/[-_]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");

function floatLiteral(value: number): string {
  return `${Number.isInteger(value) ? value.toFixed(1) : value}f`;
}

function enumLines(name: string, values: readonly string[]): string[] {
  return [`enum class ${name} : uint8_t {`, ...values.map((value, i) => `  ${pascal(value)} = ${i},`), "};", ""];
}

type SlotKind = "choices" | "numbers" | "knobs";

function slotKind(field: Field): SlotKind | null {
  if (field.kind === "enum") return "choices";
  if (field.kind === "number") return "numbers";
  if (field.kind === "knob") return "knobs";
  return null;
}

// Gives each of a layer's fields its place in the decoded layer's arrays, with blend and opacity
// first so they're in slot 0 for every type.
function assignSlots(type: LayerType): Map<string, number> {
  const counts: Record<SlotKind, number> = { choices: 1, numbers: 0, knobs: 1 };
  const slots = new Map<string, number>();
  for (const field of fieldsFor(type)) {
    if (field.key === "blend" || field.key === "opacity") {
      slots.set(field.key, 0);
      continue;
    }
    const kind = slotKind(field);
    if (kind) slots.set(field.key, counts[kind]++);
  }
  return slots;
}

function fieldRow(field: Field, slot: number): string {
  const comment = `  // ${field.key}`;
  switch (field.kind) {
    case "palette":
      return `  {RecipeFieldKind::Palette, 0, 0.0f, 0.0f},${comment}`;
    case "enum":
      return `  {RecipeFieldKind::Choice, ${slot}, 0.0f, ${floatLiteral(field.options.length - 1)}},${comment}`;
    case "number":
      return `  {RecipeFieldKind::${field.integer ? "Whole" : "Fraction"}, ${slot}, ${floatLiteral(field.min)}, ${floatLiteral(field.max)}},${comment}`;
    case "knob":
      return `  {RecipeFieldKind::Knob, ${slot}, ${floatLiteral(field.min)}, ${floatLiteral(field.max)}},${comment}`;
  }
}

// The longest trail or comet any layer can have, which sizes the engine's table of their colors.
function maxTailPixels(): number {
  const lengths = LAYER_CODES.flatMap((type) => fieldsFor(type)).flatMap((field) => (field.key === "length" && field.kind === "number" ? [field.max] : []));
  return Math.max(...lengths);
}

export function recipeTablesHeader(): string {
  const types = LAYER_CODES;
  const max: Record<SlotKind, number> = { choices: 0, numbers: 0, knobs: 0 };
  const slotLines: string[] = [];
  const tableLines: string[] = [];

  for (const type of types) {
    const slots = assignSlots(type);
    const fields = fieldsFor(type);
    for (const kind of ["choices", "numbers", "knobs"] as const) {
      const count = fields.filter((field) => slotKind(field) === kind).length;
      max[kind] = Math.max(max[kind], count);
    }
    for (const field of fields) {
      if (field.key === "blend" || field.key === "opacity" || !slots.has(field.key)) continue;
      slotLines.push(`  constexpr uint8_t ${pascal(type)}${pascal(field.key)} = ${slots.get(field.key)};`);
    }
    tableLines.push(
      `constexpr RecipeFieldInfo RECIPE_${type.toUpperCase()}_FIELDS[] = {`,
      ...fields.map((field) => fieldRow(field, slots.get(field.key) ?? 0)),
      "};",
      "",
    );
  }

  return [
    "#pragma once",
    "",
    "// Generated by `bun run build-recipes` from designer/src/recipe/spec.ts and types.ts. Don't edit",
    "// it by hand. It's the recipe format's numbers and field layout, for firewalker_recipe.h.",
    "",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
    "namespace Firewalker {",
    "",
    `constexpr uint8_t RECIPE_MIN_VERSION = ${MIN_RECIPE_VERSION};`,
    `constexpr uint8_t RECIPE_VERSION = ${RECIPE_VERSION};`,
    `constexpr size_t RECIPE_MAX_BYTES = ${MAX_COMPILED_BYTES};`,
    `constexpr uint8_t RECIPE_MAX_LAYERS = ${MAX_LAYERS};`,
    `constexpr uint8_t RECIPE_MAX_PALETTE_STOPS = ${MAX_PALETTE_STOPS};`,
    `constexpr uint8_t RECIPE_MAX_NAME_LENGTH = ${MAX_NAME_LENGTH};`,
    `constexpr uint16_t RECIPE_WAVE_PERIOD_MIN = ${WAVE_PERIOD.min};`,
    `constexpr uint16_t RECIPE_WAVE_PERIOD_MAX = ${WAVE_PERIOD.max};`,
    `constexpr uint16_t RECIPE_STOMP_FADE_MIN = ${STOMP_FADE.min};`,
    `constexpr uint16_t RECIPE_STOMP_FADE_MAX = ${STOMP_FADE.max};`,
    `constexpr uint8_t RECIPE_MAX_CHOICES = ${max.choices};`,
    `constexpr uint8_t RECIPE_MAX_NUMBERS = ${max.numbers};`,
    `constexpr uint8_t RECIPE_MAX_KNOBS = ${max.knobs};`,
    `constexpr uint8_t RECIPE_MAX_TAIL_PIXELS = ${maxTailPixels()};`,
    "",
    "// Names a recipe can't take.",
    `constexpr const char* const RECIPE_RESERVED_NAMES[] = {${[...RESERVED_NAMES].map((name) => `"${name}"`).join(", ")}};`,
    "",
    ...enumLines("RecipeLayerType", types),
    ...enumLines("RecipeSource", SOURCES),
    ...enumLines("RecipeBlend", BLENDS),
    ...enumLines("RecipeTrigger", TRIGGERS),
    ...enumLines("RecipeSpread", SPREADS),
    ...enumLines("RecipeTrailOrigin", TRAIL_ORIGINS),
    ...enumLines("RecipeChasePath", CHASE_PATHS),
    "enum class RecipeFieldKind : uint8_t {",
    "  Choice,    // 1 byte: an option's number",
    "  Whole,     // 2 bytes: a uint16",
    "  Fraction,  // 2 bytes: a scaled int16",
    "  Palette,   // 1 byte for the count, then 3 per color",
    "  Knob,      // 2 bytes if fixed: a scaled int16. See the layer's bound-knob mask",
    "};",
    "",
    "// One field, in binary order. `slot` is its place in the decoded layer's array for its kind.",
    "// A Choice's `max` is its highest option.",
    "struct RecipeFieldInfo {",
    "  RecipeFieldKind kind;",
    "  uint8_t slot;",
    "  float min;",
    "  float max;",
    "};",
    "",
    "// Where each field goes in a decoded layer. A layer's blend and opacity are in slot 0.",
    "constexpr uint8_t RECIPE_BLEND_SLOT = 0;",
    "constexpr uint8_t RECIPE_OPACITY_SLOT = 0;",
    "namespace RecipeSlot {",
    ...slotLines,
    "}  // namespace RecipeSlot",
    "",
    ...tableLines,
    "struct RecipeLayerInfo {",
    "  const RecipeFieldInfo* fields;",
    "  uint8_t count;",
    "};",
    "",
    "// Indexed by RecipeLayerType.",
    "constexpr RecipeLayerInfo RECIPE_LAYERS[] = {",
    ...types.map((type) => `  {RECIPE_${type.toUpperCase()}_FIELDS, ${fieldsFor(type).length}},`),
    "};",
    "",
    "}  // namespace Firewalker",
    "",
  ].join("\n");
}
