// Writes include/generated/recipe_builtins.h: the compiled bytes of the recipes every boot ships with.
// patterns/built-ins.txt says which ones. Being in patterns/ means a recipe is kept in the repo, and
// being on that list means it's built into the firmware.
//
// No Node imports here. server/builtins.ts does the file reading and hashing, and it's what the dev
// server's Save and `bun run build-recipes` both use.

import { compileRecipe } from "./compile.ts";
import type { Recipe } from "./types.ts";

// Keeps the `patterns` reply under its line limit. See PATTERN_LIST_MAX in firewalker_pattern_list.h.
export const MAX_BUILT_INS = 16;

// The names in a list file: one per line, with blank lines and `#` comments ignored.
export function parseBuiltInList(text: string): string[] {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line !== "" && !line.startsWith("#"));
}

// Replaces or removes one name in a list file, leaving its comments and everything else as written.
export function renameInBuiltInList(text: string, name: string, replacement: string | null): string {
  const lines = text.split("\n");
  const updated = lines.flatMap((line) => {
    if (line.trim() !== name) return [line];
    return replacement === null ? [] : [replacement];
  });
  return updated.join("\n");
}

const arrayName = (name: string) => `BUILTIN_${name.toUpperCase().replace(/-/g, "_")}`;

// `recipes` holds a recipe for each name, in list order, and `sourceHash` identifies the list and
// those files. tools/pio/recipe_check.py recomputes the hash to catch a stale header. Throws with a
// plain reason if a recipe can't be built in.
export function builtinsHeader(recipes: Recipe[], sourceHash: string): string {
  if (recipes.length > MAX_BUILT_INS) throw new Error(`patterns/built-ins.txt lists ${recipes.length} recipes. The most is ${MAX_BUILT_INS}.`);
  const compiled = recipes.map((recipe) => {
    const result = compileRecipe(recipe);
    if (!result.ok) throw new Error(`${recipe.name} can't be built in: ${result.errors.join(" ")}`);
    return { name: recipe.name, bytes: result.bytes };
  });

  const count = compiled.length;
  return [
    "#pragma once",
    "",
    "// Generated by `bun run build-recipes` from patterns/built-ins.txt. Don't edit it by hand. A firmware",
    "// build fails if this is out of date, using the hash on the next line.",
    `// source-hash: ${sourceHash}`,
    "",
    '#include "firewalker_pattern_list.h"',
    "",
    "namespace Firewalker {",
    "",
    ...compiled.map(({ name, bytes }) => `static const uint8_t ${arrayName(name)}[] = {${[...bytes].join(", ")}};`),
    "",
    `constexpr uint8_t RECIPE_BUILTIN_COUNT = ${count};`,
    // An array can't be empty in C++, so a list with nothing on it still has one unused row.
    `static const BuiltInRecipe RECIPE_BUILTINS[${Math.max(1, count)}] = {`,
    ...(count === 0 ? ['  {"", nullptr, 0},'] : compiled.map(({ name, bytes }) => `  {"${name}", ${arrayName(name)}, ${bytes.length}},`)),
    "};",
    "",
    "}  // namespace Firewalker",
    "",
  ].join("\n");
}
